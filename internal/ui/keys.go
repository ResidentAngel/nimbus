package ui

import tea "github.com/charmbracelet/bubbletea"

// ruToLatin сопоставляет клавиши русской раскладки ЙЦУКЕН латинским буквам
// на тех же местах, чтобы горячие клавиши (f, n, b, q, h…) работали,
// даже если включена русская раскладка: «а» — это f, «т» — n и т.д.
var ruToLatin = map[rune]rune{
	'й': 'q', 'ц': 'w', 'у': 'e', 'к': 'r', 'е': 't', 'н': 'y', 'г': 'u', 'ш': 'i', 'щ': 'o', 'з': 'p',
	'ф': 'a', 'ы': 's', 'в': 'd', 'а': 'f', 'п': 'g', 'р': 'h', 'о': 'j', 'л': 'k', 'д': 'l',
	'я': 'z', 'ч': 'x', 'с': 'c', 'м': 'v', 'и': 'b', 'т': 'n', 'ь': 'm',
	'Й': 'Q', 'Ц': 'W', 'У': 'E', 'К': 'R', 'Е': 'T', 'Н': 'Y', 'Г': 'U', 'Ш': 'I', 'Щ': 'O', 'З': 'P',
	'Ф': 'A', 'Ы': 'S', 'В': 'D', 'А': 'F', 'П': 'G', 'Р': 'H', 'О': 'J', 'Л': 'K', 'Д': 'L',
	'Я': 'Z', 'Ч': 'X', 'С': 'C', 'М': 'V', 'И': 'B', 'Т': 'N', 'Ь': 'M',
	'.': '/', // «/» на русской раскладке — это «.» на той же клавише
}

// latinKey возвращает название клавиши с учётом русской раскладки.
func latinKey(k tea.KeyMsg) string {
	if k.Type == tea.KeyRunes && len(k.Runes) == 1 && !k.Alt {
		if r, ok := ruToLatin[k.Runes[0]]; ok {
			return string(r)
		}
	}
	return k.String()
}
